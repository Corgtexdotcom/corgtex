import {randomUUID} from "node:crypto";
import {beforeEach, describe, expect, it} from "vitest";
import {prisma, type AppActor} from "@corgtex/shared";
import {truncateAllTables} from "../../shared/src/db-test-utils";
import {advanceHumanArtifactInputLineage, captureArtifactInputProof, copyArtifactInputLineage,
  createBrainArticleHistoryVersion, readableArtifactIds, recordArtifactInputLineage} from "./source-lineage";

async function fixture() {
  const workspace=await prisma.workspace.create({data:{name:"Synthetic history birth",slug:`history-birth-${randomUUID()}`}});
  const user=await prisma.user.create({data:{email:`history-birth-${randomUUID()}@example.test`,displayName:"Synthetic Owner",passwordHash:"synthetic"}});
  const member=await prisma.member.create({data:{workspaceId:workspace.id,userId:user.id,role:"ADMIN"}});
  const actor:AppActor={kind:"user",user};
  const article=await prisma.brainArticle.create({data:{workspaceId:workspace.id,slug:"original",type:"STRATEGY",title:"Independent original",bodyMd:"Exact original bytes",isPrivate:false}});
  await prisma.$transaction(tx=>recordArtifactInputLineage({tx,actor,workspaceId:workspace.id,
    artifact:{kind:"BrainArticle",id:article.id},content:article,origin:"HUMAN_ORIGINAL",inputs:[]}));
  return {workspace,user,member,actor,article};
}

describe("trusted newborn Article history constructor",()=>{
  beforeEach(truncateAllTables);
  it("adds only the new Version own epoch to exact derived source evidence",async()=>{
    const f=await fixture();
    const inputs=await captureArtifactInputProof(f.actor,f.workspace.id,[{kind:"BrainArticle",id:f.article.id}]);
    const derived=await prisma.brainArticle.create({data:{workspaceId:f.workspace.id,slug:"derived",type:"STRATEGY",title:"Derived",bodyMd:"Exact generated bytes",isPrivate:false}});
    await prisma.$transaction(tx=>recordArtifactInputLineage({tx,actor:f.actor,workspaceId:f.workspace.id,
      artifact:{kind:"BrainArticle",id:derived.id},content:derived,origin:"DERIVED",inputs:[],inheritedRoots:inputs}));
    const prior=await prisma.artifactInputLineage.findFirstOrThrow({where:{artifactType:"BrainArticle",artifactId:derived.id},orderBy:{revision:"desc"}});
    const saved=structuredClone(prior);
    const history=await prisma.$transaction(tx=>createBrainArticleHistoryVersion({tx,workspaceId:f.workspace.id,
      article:derived,version:1,reason:"BODY_EDIT",preserveKnownHistory:true}));
    expect(history.preserved).toBe(true);
    const copied=await prisma.artifactInputLineage.findFirstOrThrow({where:{artifactType:"BrainArticleVersion",artifactId:history.version.id}});
    expect(copied.rootsJson).toEqual(prior.rootsJson);expect(copied.inputsJson).toEqual(prior.inputsJson);
    const entries=(copied.permissionEpochsJson as any).entries;
    expect(entries.filter((entry:any)=>entry.kind!=="BrainArticleVersion"||entry.id!==history.version.id))
      .toEqual((prior.permissionEpochsJson as any).entries);
    expect(entries.filter((entry:any)=>entry.kind==="BrainArticleVersion"&&entry.id===history.version.id)).toHaveLength(1);
    expect(await prisma.artifactInputLineage.findUnique({where:{id:prior.id}})).toEqual(saved);
    expect((await readableArtifactIds(f.actor,f.workspace.id,"BrainArticleVersion",[history.version])).has(history.version.id)).toBe(true);
  });

  it("preserves genuine H0 history after restore without requiring its creation vector current",async()=>{
    const f=await fixture();
    await prisma.$transaction(async tx=>{
      const privateRow=await tx.brainArticle.update({where:{id:f.article.id},data:{isPrivate:true,ownerMemberId:f.member.id}});
      await advanceHumanArtifactInputLineage({tx,actor:f.actor,workspaceId:f.workspace.id,
        artifact:{kind:"BrainArticle",id:f.article.id},before:f.article,after:privateRow});
      const restored=await tx.brainArticle.update({where:{id:f.article.id},data:{isPrivate:false,ownerMemberId:null}});
      await advanceHumanArtifactInputLineage({tx,actor:f.actor,workspaceId:f.workspace.id,
        artifact:{kind:"BrainArticle",id:f.article.id},before:privateRow,after:restored});
      const prior=await tx.artifactInputLineage.findFirstOrThrow({where:{artifactType:"BrainArticle",artifactId:f.article.id},orderBy:{revision:"desc"}});
      const history=await createBrainArticleHistoryVersion({tx,workspaceId:f.workspace.id,
        article:restored,version:1,reason:"BODY_EDIT",preserveKnownHistory:true});
      expect(history.preserved).toBe(true);
      const copied=await tx.artifactInputLineage.findFirstOrThrow({where:{artifactType:"BrainArticleVersion",artifactId:history.version.id}});
      expect((copied.permissionEpochsJson as any).entries.filter((entry:any)=>entry.kind!=="BrainArticleVersion"))
        .toEqual((prior.permissionEpochsJson as any).entries);
      expect((await readableArtifactIds(f.actor,f.workspace.id,"BrainArticleVersion",[history.version],tx)).has(history.version.id)).toBe(true);
    });
  });

  it("rejects existing Version promotion and forged birth receipts",async()=>{
    const f=await fixture();
    const version=await prisma.brainArticleVersion.create({data:{articleId:f.article.id,version:1,bodyMd:f.article.bodyMd,
      accessEnvelopeJson:{isPrivate:false,ownerMemberId:null}}});
    expect(await prisma.$transaction(tx=>copyArtifactInputLineage({tx,workspaceId:f.workspace.id,
      from:{kind:"BrainArticle",id:f.article.id},fromContent:f.article,
      to:{kind:"BrainArticleVersion",id:version.id},toContent:version,birth:Object.freeze({})}))).toBe(false);
    await expect(prisma.$transaction(tx=>createBrainArticleHistoryVersion({tx,workspaceId:f.workspace.id,
      article:f.article,version:2,id:version.id,reason:"BODY_EDIT",preserveKnownHistory:true}))).rejects.toMatchObject({code:"P2002"});
    expect(await prisma.artifactInputLineage.count({where:{artifactType:"BrainArticleVersion",artifactId:version.id}})).toBe(0);
  });

  it("keeps revoked DERIVED history unknown during independently reviewed regeneration",async()=>{
    const f=await fixture(),inputs=await captureArtifactInputProof(f.actor,f.workspace.id,[{kind:"BrainArticle",id:f.article.id}]);
    const derived=await prisma.brainArticle.create({data:{workspaceId:f.workspace.id,slug:"old-derived",type:"STRATEGY",title:"Derived",bodyMd:"Old generated bytes",isPrivate:false}});
    await prisma.$transaction(tx=>recordArtifactInputLineage({tx,actor:f.actor,workspaceId:f.workspace.id,
      artifact:{kind:"BrainArticle",id:derived.id},content:derived,origin:"DERIVED",inputs:[],inheritedRoots:inputs}));
    await prisma.brainArticle.update({where:{id:f.article.id},data:{isPrivate:true,ownerMemberId:f.member.id}});
    await prisma.brainArticle.update({where:{id:f.article.id},data:{isPrivate:false,ownerMemberId:null}});
    const history=await prisma.$transaction(tx=>createBrainArticleHistoryVersion({tx,workspaceId:f.workspace.id,
      article:derived,version:1,reason:"REVIEWED_SOURCE_REGENERATION",preserveKnownHistory:true}));
    expect(history.preserved).toBe(false);
    expect(history.version.changeSummary).toBe("Previous body before reviewed source regeneration.");
    expect(history.version.bodyMd).toBe(derived.bodyMd);
    const manifest=await prisma.artifactInputLineage.findFirstOrThrow({where:{artifactType:"BrainArticleVersion",artifactId:history.version.id}});
    expect(manifest.origin).toBe("UNKNOWN");
    expect(await readableArtifactIds(f.actor,f.workspace.id,"BrainArticleVersion",[history.version])).toEqual(new Set());
  });
});
